import pandas as pd
import os
import numpy as np
from datetime import datetime
"""
This file is in charge of computing the error of the out-of-sample forecast period such that
the MAE, and (MSE) RMSE tests are computed exclusively over the final 554 days of the set
across all calibration lengths then averages it to formulate the LEAR-Ens point estimates.
"""
filelist = sorted(os.listdir(os.path.join('..', 'lear_forecasts'))) # sorts the list of forecast
cal_lens = set([int(e.split('_')[0]) for e in filelist]) # gets the different calibration windows
cal_lens = sorted(list(cal_lens)) # sort the calibration window set
cl_dfs = {}
for cl in cal_lens:
    singledfs = []
    subfilelist = [e for e in filelist if e.startswith(str(cl))]# [182:]
    for f in subfilelist:  # loops through all the files generated by lear.py
        temp = pd.read_csv(os.path.join('..', 'lear_forecasts', f), index_col=0) # read a file from the directory of generated predictions 
        temp.index = [datetime.strptime(e, '%Y-%m-%d %H:%M:%S') for e in temp.index] # set the datetime index
        singledfs.append(temp) # each file get allocated to memory in singledfs
    
    wholeindex = [] # container for the indices of the whole period
    for e in singledfs:
        for i in e.index:
            wholeindex.append(i)
    
    wholedf = pd.DataFrame(index=wholeindex, columns=['real', 'forecast']) # instantiate the df to compute error
    for e in singledfs: # get the real and forecasted values for the corresponding index in each of the df in singledfs
        wholedf.loc[e.index[:], 'real'] = e.loc[e.index[:], 'real'].to_numpy()
        wholedf.loc[e.index[:], 'forecast'] = e.loc[e.index[:], 'forecast'].to_numpy()
    
    evaldf = wholedf.iloc[182*24:] # takes the last 554 days of the out-of-sample period
    mae = np.abs((evaldf.real - evaldf.forecast).to_numpy()).mean()  # computes the mae
    rmse = np.sqrt(((evaldf.real - evaldf.forecast).to_numpy()**2).mean()) # computes the rmse
    print(f'CAL LEN: {cl}') # prints the prefix of the file name
    print(f'MAE: {mae}\t\tRMSE: {rmse}\tbased on {len(evaldf)/24} days') #prints the respective errors
    # wholedf.to_csv(f'lear_forecast_{cl}.csv')
    cl_dfs[cl] = wholedf # builds the dictionnary with df attached to its file prefix as key

wholedf = cl_dfs[cal_lens[0]] #initialise the prediction dataframe with the first calibration window df
wholedf.columns = ['real', f'forecast{cal_lens[0]}'] #reinstate the column names
for cl in cal_lens[1:]: # gets the forcast of the rest of the calibration windows
    temp = cl_dfs[cl]
    wholedf.loc[temp.index[:], f'forecast{cl}'] = temp.loc[temp.index[:], 'forecast'].to_numpy()
wholedf.loc[wholedf.index[:], 'forecast_averaged'] = wholedf.drop(columns='real').mean(axis='columns').to_numpy() # compute the prediction aka the average of the different calibration windows
wholedf.to_csv(f'lear_forecast.csv') # saving
wholedf = wholedf.iloc[182*24:] # exclude the 182 days to stay comparable to the QRA and QRM models that require part of the ofs period to execute the quantile regression
mae = np.abs((wholedf.real - wholedf.forecast_averaged).to_numpy()).mean()
rmse = np.sqrt(((wholedf.real - wholedf.forecast_averaged).to_numpy()**2).mean())
print(f'ENSEMBLE OF 4 LENGTHS')
print(f'MAE: {mae}\t\tRMSE: {rmse}\tbased on {len(wholedf)/24} days')
